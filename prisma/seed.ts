// ---------------------------------------------------------------------------
// Main seed function
// ---------------------------------------------------------------------------
async function main() {
  console.log('🌱 Starting database seed…');

  // 1. Upsert categories
  const categoryMap: Record<string, string> = {};
  for (const cat of categories) {
    const record = await prisma.category.upsert({
      where: { slug: cat.slug },
      create: {
        slug: cat.slug,
        name: cat.name,
        description: cat.description,
        icon: cat.icon,
        sortOrder: cat.sortOrder,
        isActive: true,
      },
      update: {
        name: cat.name,
        description: cat.description,
        icon: cat.icon,
        sortOrder: cat.sortOrder,
      },
    });
    categoryMap[cat.slug] = record.id;
    console.log(`  ✅ Category: ${cat.name}`);
  }

  // 2. Upsert products + inventory
  for (const p of products) {
    const categoryId = categoryMap[p.categorySlug];
    if (!categoryId) {
      console.warn(`  ⚠️  Unknown category slug "${p.categorySlug}" for product "${p.name}" — skipping`);
      continue;
    }

    const product = await prisma.product.upsert({
      where: { slug: p.slug },
      create: {
        slug: p.slug,
        sku: ('sku' in p ? p.sku : null) as string | null,
        name: p.name,
        description: p.description,
        categoryId,
        subCategory: p.subCategory ?? null,
        price: p.price,
        originalPrice: p.originalPrice,
        discount: p.discount,
        rating: p.rating,
        reviewCount: p.reviewCount,
        images: JSON.stringify(p.images),
        features: JSON.stringify(p.features),
        specifications: JSON.stringify(p.specifications),
        badge: p.badge ?? null,
        featured: p.featured,
        isBundle: ('isBundle' in p ? Boolean(p.isBundle) : false),
        isDemo: true,
        isActive: true,
        status: 'published',
      },
      update: {
        sku: ('sku' in p ? p.sku : null) as string | null,
        name: p.name,
        description: p.description,
        categoryId,
        subCategory: p.subCategory ?? null,
        price: p.price,
        originalPrice: p.originalPrice,
        discount: p.discount,
        rating: p.rating,
        reviewCount: p.reviewCount,
        images: JSON.stringify(p.images),
        features: JSON.stringify(p.features),
        specifications: JSON.stringify(p.specifications),
        badge: p.badge ?? null,
        featured: p.featured,
        isBundle: ('isBundle' in p ? Boolean(p.isBundle) : false),
        status: 'published',
      },
    });

    await prisma.inventory.upsert({
      where: { productId: product.id },
      create: {
        productId: product.id,
        stockCount: p.stockCount,
        reserved: 0,
        lowStockAlert: 5,
      },
      update: {
        stockCount: p.stockCount,
        lowStockAlert: 5,
      },
    });

    console.log(`  ✅ Product: ${p.name}`);
  }

  // 3. Link Bundle components for brother-bt5000-set4
  const bundleProduct = await prisma.product.findUnique({ where: { slug: 'brother-bt5000-set4' } });
  if (bundleProduct) {
    const componentSlugs = [
      'brother-bt5000c',
      'brother-bt5000m',
      'brother-bt5000y',
      'brother-btd60bk',
    ];
    for (const compSlug of componentSlugs) {
      const comp = await prisma.product.findUnique({ where: { slug: compSlug } });
      if (comp) {
        await prisma.bundleItem.upsert({
          where: {
            bundleProductId_componentProductId: {
              bundleProductId: bundleProduct.id,
              componentProductId: comp.id,
            },
          },
          create: {
            bundleProductId: bundleProduct.id,
            componentProductId: comp.id,
            quantity: 1,
          },
          update: {
            quantity: 1,
          },
        });
      }
    }
    console.log(`  🔗 Bundle Components linked for: ${bundleProduct.name}`);
  }

  console.log(`\n✅ Seeded ${categories.length} categories and ${products.length} products.`);
}

main()
  .catch((e) => {
    console.error('❌ Seed failed:', e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
